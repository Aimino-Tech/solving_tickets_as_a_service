function scoreTask(_task: PlanBenchTask, output: string): number {
  const keywords = ["plan", "step", "implement", "use", "migrate", "architect", "design", "approach", "strategy", "consider"];
  const lower = output.toLowerCase();
  let score = 0;
  for (const kw of keywords) {
    if (lower.includes(kw)) score += 0.05;
  }
  return Math.min(score, 1);
}

function estimateCost(task: PlanBenchTask, _result: PlanBenchResult): number {
  const totalChars = task.description.length + task.context.length + _result.output.length;
  const tokens = totalChars / 3;
  return parseFloat(((tokens / 1_000_000) * 3).toFixed(6));
}

async function executeTask(task: PlanBenchTask, config: PlanBenchConfig): Promise<PlanBenchResult> {
  const startTime = Date.now();
  const prompt = `You are a senior software architect. Given the following task, produce a detailed plan.

Category: ${task.category}
Description: ${task.description}
Context: ${task.context}
Hints: ${task.hints.join(", ")}

Output a structured plan covering approach, steps, and considerations.`;
  const cost = estimateCost(task, { taskId: task.taskId, correct: false, score: 0, output: "", error: null, durationMs: 0, costUsd: 0 });
  try {
    const response = await fetch(
      process.env.OPENAI_API_URL || "https://api.openai.com/v1/chat/completions",
      {
        method: "POST",
        headers: {
          "Content-Type": "application/json",
          Authorization: `Bearer ${process.env.OPENAI_API_KEY}`,
        },
        body: JSON.stringify({
          model: config.model,
          messages: [{ role: "user", content: prompt }],
          temperature: config.temperature,
          max_tokens: config.maxTokens,
        }),
      }
    );
    const data: any = await response.json();
    const output = data.choices?.[0]?.message?.content || "";
    const score = scoreTask(task, output);
    const correct = score >= 0.5;
    return {
      taskId: task.taskId,
      correct,
      score,
      output: output.slice(0, 1000),
      error: null,
      durationMs: Date.now() - startTime,
      costUsd: cost,
    };
  } catch (err: any) {
    return {
      taskId: task.taskId,
      correct: false,
      score: 0,
      output: "",
      error: err.message ?? String(err),
      durationMs: Date.now() - startTime,
      costUsd: cost,
    };
  }
}

export async function runPlanBench(config: PlanBenchConfig): Promise<PlanBenchReport> {
  const tasks = TASKS.slice(0, config.taskLimit);
  const details: PlanBenchResult[] = [];
  const byCategory: Record<string, { total: number; correct: number; accuracy: number }> = {};

  for (const task of tasks) {
    const result = await executeTask(task, config);
    details.push(result);
    if (!byCategory[task.category]) {
      byCategory[task.category] = { total: 0, correct: 0, accuracy: 0 };
    }
    byCategory[task.category].total++;
    if (result.correct) byCategory[task.category].correct++;
    console.log(`[${task.taskId}] ${result.correct ? "CORRECT" : "WRONG"} (score: ${result.score.toFixed(2)})`);
  }

  for (const cat of Object.keys(byCategory)) {
    byCategory[cat].accuracy = byCategory[cat].correct / byCategory[cat].total;
  }

  const total = details.length;
  const correct = details.filter((d) => d.correct).length;
  const report: PlanBenchReport = {
    benchmark: "planbench",
    runId: `planbench-${Date.now().toString(36)}`,
    timestamp: new Date().toISOString(),
    commit: (() => { try { return execSync("git rev-parse HEAD", { encoding: "utf-8" }).trim(); } catch { return "unknown"; } })(),
    config,
    results: {
      total,
      correct,
      accuracy: total > 0 ? correct / total : 0,
      byCategory,
      avgTimePerTask: total > 0 ? Math.round(details.reduce((s, d) => s + d.durationMs, 0) / total) : 0,
    },
    details,
  };

  const resultsDir = join(__dirname, "..", "results");
  if (!existsSync(resultsDir)) mkdirSync(resultsDir, { recursive: true });
  writeFileSync(join(resultsDir, `${Date.now()}-planbench.json`), JSON.stringify(report, null, 2));

  return report;
}
