interface PlanBenchTask {
  taskId: string;
  category: "planning" | "reasoning" | "constraints" | "dependencies";
  description: string;
  context: string;
  expectedOutput: string;
  hints: string[];
}

interface PlanBenchConfig {
  model: string;
  temperature: number;
  maxTokens: number;
  taskLimit: number;
  retryCount: number;
}

interface PlanBenchResult {
  taskId: string;
  correct: boolean;
  score: number;
  output: string;
  error: string | null;
  durationMs: number;
  costUsd: number;
}

interface PlanBenchReport {
  benchmark: "planbench";
  runId: string;
  timestamp: string;
  commit: string;
  config: PlanBenchConfig;
  results: {
    total: number;
    correct: number;
    accuracy: number;
    byCategory: Record<string, { total: number; correct: number; accuracy: number }>;
    avgTimePerTask: number;
  };
  details: PlanBenchResult[];
}

